function buildTafsirDeck(surah) {
  const ayahs = tafsirAyahs(surah);
  return shuffleTafsir([
    ...ayahs.map((ayah) => ({ ...ayah, type: "ayah", direction: "ayah-to-meaning" })),
    ...ayahs.map((ayah) => ({ ...ayah, type: "ayah", direction: "meaning-to-ayah" })),
    {
      type: "theme",
      surahNumber: surah.number,
      surahName: surah.name,
      arabicSurahName: surah.quran.arabicName,
      theme: surah.theme
    },
    {
      type: "revelation",
      surahNumber: surah.number,
      surahName: surah.name,
      arabicSurahName: surah.quran.arabicName,
      revelation: surah.revelation
    },
    {
      type: "virtue",
      surahNumber: surah.number,
      surahName: surah.name,
      arabicSurahName: surah.quran.arabicName,
      virtue: surah.virtue
    },
    {
      type: "evidence",
      surahNumber: surah.number,
      surahName: surah.name,
      arabicSurahName: surah.quran.arabicName,
      evidenceAnswer: surah.evidenceAnswer
    },
    ...tafsirDetails(surah).map((detail) => ({ ...detail, type: "detail" })),
    ...tafsirFamousAyahs(surah).map((ayah) => ({ ...ayah, type: "famous" }))
  ]);
}

function startTafsirTest() {
  if (!tafsirState.selected) return;
  tafsirState.deck = buildTafsirDeck(tafsirState.selected);
  tafsirState.index = 0;
  tafsirState.score = 0;
  tafsirState.errors = [];
  showTafsirPanel("test");
  renderTafsirQuestion();
  tafsirElement("tafsir-test").scrollIntoView({ behavior: "smooth", block: "start" });
}

function uniqueTafsirOptions(current, key) {
  const correct = current[key];
  const seen = new Set([correct]);
  const distractors = [];
  for (const candidate of shuffleTafsir(ALL_TAFSIR_AYAHS)) {
    if (candidate.surahNumber === current.surahNumber && candidate.number === current.number) continue;
    if (seen.has(candidate[key])) continue;
    seen.add(candidate[key]);
    distractors.push(candidate);
    if (distractors.length === 3) break;
  }
  return shuffleTafsir([current, ...distractors]);
}

function renderTafsirQuestion() {
  const current = tafsirState.deck[tafsirState.index];
  tafsirState.revealed = false;
  tafsirState.answered = false;
  const isTheme = current.type === "theme";
  const isRevelation = current.type === "revelation";
  const isVirtue = current.type === "virtue";
  const isEvidence = current.type === "evidence";
  const isDetail = current.type === "detail";
  const isFamous = current.type === "famous";
  const isArabicPrompt = current.type === "ayah" && current.direction === "ayah-to-meaning";
  let options;
  let correctValue;
  let display;
  let prompt;
  let reference;
  let answersAreArabic = false;

  if (isTheme) {
    options = shuffleTafsir(TAFSIR_SURAHS.map((surah) => ({ value: surah.theme })));
    correctValue = current.theme;
    display = current.arabicSurahName;
    prompt = "Выбери главную тему суры";
    reference = "Главная тема";
  } else if (isRevelation) {
    options = shuffleTafsir(TAFSIR_SURAHS.map((surah) => ({ value: surah.revelation })));
    correctValue = current.revelation;
    display = current.arabicSurahName;
    prompt = "Выбери обстоятельства ниспослания этой суры";
    reference = "Ниспослание";
  } else if (isVirtue) {
    options = shuffleTafsir(TAFSIR_SURAHS.map((surah) => ({ value: surah.virtue })));
    correctValue = current.virtue;
    display = current.arabicSurahName;
    prompt = "Выбери достоинства и значение этой суры";
    reference = "Достоинства";
  } else if (isEvidence) {
    options = shuffleTafsir(TAFSIR_SURAHS.map((surah) => ({ value: surah.evidenceAnswer })));
    correctValue = current.evidenceAnswer;
    display = current.arabicSurahName;
    prompt = "Выбери самое точное объяснение достоверности сообщений";
    reference = "Проверяем источники";
  } else if (isDetail) {
    const seen = new Set([current.answer]);
    const detailOptions = [current];
    for (const detail of shuffleTafsir(ALL_TAFSIR_DETAILS)) {
      if (seen.has(detail.answer)) continue;
      seen.add(detail.answer);
      detailOptions.push(detail);
      if (detailOptions.length === 5) break;
    }
    options = shuffleTafsir(detailOptions.map((detail) => ({ value: detail.answer })));
    correctValue = current.answer;
    display = current.question;
    prompt = "Выбери правильное объяснение";
    reference = current.title;
  } else if (isFamous) {
    const famousOptions = uniqueTafsirOptions(current, "arabic");
    options = famousOptions.map((ayah) => ({ value: ayah.arabic }));
    correctValue = current.arabic;
    display = current.note;
    prompt = "Выбери знаменитый или ключевой аят по его смыслу";
    reference = `Ключевой аят ${current.number}`;
    answersAreArabic = true;
  } else {
    options = uniqueTafsirOptions(current, isArabicPrompt ? "summary" : "arabic")
      .map((ayah) => ({ value: isArabicPrompt ? ayah.summary : ayah.arabic }));
    correctValue = isArabicPrompt ? current.summary : current.arabic;
    display = isArabicPrompt ? current.arabic : current.summary;
    prompt = isArabicPrompt ? "Выбери краткий смысл аята" : "Найди аят по его краткому смыслу";
    reference = `Аят ${current.number}`;
    answersAreArabic = !isArabicPrompt;
  }
  const progress = (tafsirState.index / tafsirState.deck.length) * 100;
  const promptIsArabic = isTheme || isRevelation || isVirtue || isEvidence || isArabicPrompt;

  tafsirElement("tafsir-test").innerHTML = `
    <div class="tafsir-test-head">
      <button id="exit-tafsir-test">← К изучению суры</button>
      <div><span>Задание ${tafsirState.index + 1} из ${tafsirState.deck.length}</span><strong>Верно ${tafsirState.score}</strong></div>
      <div class="progress-track"><span style="width:${progress}%"></span></div>
    </div>
    <div class="tafsir-question">
      <div class="ayah-reference"><span>Сура ${current.surahNumber}. ${tafsirEscape(current.surahName)}</span><strong>${reference}</strong></div>
      <p class="prompt">${prompt}</p>
      <div class="tafsir-prompt ${promptIsArabic ? "arabic" : "meaning"}" ${promptIsArabic ? 'dir="rtl" lang="ar"' : ""}>${tafsirEscape(display)}</div>
      <button class="reveal-answers" id="reveal-tafsir-answers">Показать варианты ответов</button>
      <div class="tafsir-answer-list" id="tafsir-answer-list" hidden>
        ${options.map((option, index) => {
          const content = answersAreArabic
            ? `<b dir="rtl" lang="ar">${tafsirEscape(option.value)}</b>`
            : tafsirEscape(option.value);
          return `<button class="tafsir-answer ${answersAreArabic ? "arabic-answer" : ""}" data-option="${index}"><span>${index + 1}</span><span>${content}</span></button>`;
        }).join("")}
      </div>
      <div id="tafsir-feedback"></div>
    </div>`;

  tafsirElement("exit-tafsir-test").addEventListener("click", () => openTafsirStudy(tafsirState.selected.number));
  tafsirElement("reveal-tafsir-answers").addEventListener("click", () => {
    tafsirState.revealed = true;
    tafsirElement("reveal-tafsir-answers").hidden = true;
    tafsirElement("tafsir-answer-list").hidden = false;
  });

  document.querySelectorAll(".tafsir-answer").forEach((button) => button.addEventListener("click", () => {
    if (!tafsirState.revealed || tafsirState.answered) return;
    const option = options[Number(button.dataset.option)];
    const correct = option.value === correctValue;
    tafsirState.answered = true;
    if (typeof window.playAnswerSound === "function") window.playAnswerSound(correct);
    if (correct) tafsirState.score += 1;
    else tafsirState.errors.push(current);

    document.querySelectorAll(".tafsir-answer").forEach((answer, index) => {
      answer.disabled = true;
      const answerOption = options[index];
      const answerCorrect = answerOption.value === correctValue;
      if (answerCorrect) answer.classList.add("right");
    });
    if (!correct) button.classList.add("wrong");
    renderTafsirFeedback(correct, current);
  }));
}

function renderTafsirFeedback(correct, current) {
  const isTheme = current.type === "theme";
  const correctMarkup = isTheme
    ? `<p>${tafsirEscape(current.theme)}</p>`
    : current.type === "revelation"
      ? `<p>${tafsirEscape(current.revelation)}</p>`
      : current.type === "virtue"
        ? `<p>${tafsirEscape(current.virtue)}</p>`
        : current.type === "evidence"
          ? `<p>${tafsirEscape(current.evidenceAnswer)}</p>`
          : current.type === "detail"
            ? `<p>${tafsirEscape(current.answer)}</p>`
        : current.type === "famous"
          ? `<p class="tafsir-feedback-arabic" dir="rtl" lang="ar">${tafsirEscape(current.arabic)}</p><p>${tafsirEscape(current.russian)}</p><p>${tafsirEscape(current.note)}</p>`
          : `<p class="tafsir-feedback-arabic" dir="rtl" lang="ar">${tafsirEscape(current.arabic)}</p><p>${tafsirEscape(current.summary)}</p>`;
  tafsirElement("tafsir-feedback").innerHTML = `
    <div class="tafsir-feedback ${correct ? "good" : "bad"}">
      <span class="feedback-icon">${correct ? "✓" : "↺"}</span>
      <div><strong>${correct ? "Верно!" : "Правильный ответ:"}</strong>${correct ? "" : correctMarkup}</div>
      <button id="next-tafsir-question">${tafsirState.index === tafsirState.deck.length - 1 ? "Посмотреть результат" : "Следующее задание →"}</button>
    </div>`;
  tafsirElement("next-tafsir-question").addEventListener("click", () => {
    if (tafsirState.index === tafsirState.deck.length - 1) renderTafsirResult();
    else {
      tafsirState.index += 1;
      renderTafsirQuestion();
      tafsirElement("tafsir-test").scrollIntoView({ behavior: "smooth", block: "start" });
    }
  });
}

function renderTafsirResult() {
  const total = tafsirState.deck.length;
  const percent = Math.round((tafsirState.score / total) * 100);
  showTafsirPanel("result");
  tafsirElement("tafsir-result").innerHTML = `
    <div class="tafsir-result-screen">
      <p class="eyebrow">Закрепление завершено</p>
      <div class="result-ring" style="--result:${percent * 3.6}deg"><span><strong>${percent}%</strong><small>${tafsirState.score} из ${total}</small></span></div>
      <h2>${percent >= 90 ? "Смысл суры хорошо закреплён" : percent >= 70 ? "Очень хороший результат" : "Повтори объяснения ещё раз"}</h2>
      <p>${tafsirState.errors.length ? `Ошибок: ${tafsirState.errors.length}. Посмотри объяснения, которые стоит повторить.` : "Все ответы правильные — великолепно!"}</p>
      ${tafsirState.errors.length ? `<div class="tafsir-error-list">${tafsirState.errors.map((error, index) => `
        <article><span>${index + 1}</span><div><small>${error.type === "theme" ? "Главная тема суры" : error.type === "revelation" ? "Обстоятельства ниспослания" : error.type === "virtue" ? "Достоинства суры" : error.type === "evidence" ? "Проверка источников" : error.type === "detail" ? error.title : error.type === "famous" ? `Ключевой аят ${error.number}` : `Аят ${error.number}`}</small>
          ${error.type === "theme" ? `<p>${tafsirEscape(error.theme)}</p>` : error.type === "revelation" ? `<p>${tafsirEscape(error.revelation)}</p>` : error.type === "virtue" ? `<p>${tafsirEscape(error.virtue)}</p>` : error.type === "evidence" ? `<p>${tafsirEscape(error.evidenceAnswer)}</p>` : error.type === "detail" ? `<p>${tafsirEscape(error.answer)}</p>` : error.type === "famous" ? `<p class="tafsir-feedback-arabic" dir="rtl" lang="ar">${tafsirEscape(error.arabic)}</p><p>${tafsirEscape(error.russian)}</p><p>${tafsirEscape(error.note)}</p>` : `<p class="tafsir-feedback-arabic" dir="rtl" lang="ar">${tafsirEscape(error.arabic)}</p><p>${tafsirEscape(error.summary)}</p>`}
        </div></article>`).join("")}</div>` : ""}
      <div class="result-actions"><button id="repeat-tafsir-test">↻ Пройти ещё раз</button><button id="return-tafsir-study">Повторить объяснения</button></div>
    </div>`;
  tafsirElement("repeat-tafsir-test").addEventListener("click", startTafsirTest);
  tafsirElement("return-tafsir-study").addEventListener("click", () => openTafsirStudy(tafsirState.selected.number));
  tafsirElement("tafsir-result").scrollIntoView({ behavior: "smooth", block: "start" });
}


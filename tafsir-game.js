const tafsirEscape = (value) => String(value)
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;")
  .replaceAll("'", "&#039;");

function shuffleTafsir(values) {
  const copy = [...values];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function tafsirAyahs(surah) {
  return surah.quran.ayahs.map((ayah) => ({
    ...ayah,
    surahNumber: surah.number,
    surahName: surah.name,
    summary: surah.lessons[ayah.number]
  }));
}

function tafsirAyahCountLabel(count) {
  if (count % 10 === 1 && count % 100 !== 11) return `${count} аят`;
  if ([2, 3, 4].includes(count % 10) && ![12, 13, 14].includes(count % 100)) return `${count} аята`;
  return `${count} аятов`;
}

const ALL_TAFSIR_AYAHS = TAFSIR_SURAHS.flatMap(tafsirAyahs);

function tafsirFamousAyahs(surah) {
  return surah.famous.map((famous) => {
    const ayah = surah.quran.ayahs.find((item) => item.number === famous.number);
    return {
      ...ayah,
      ...famous,
      surahNumber: surah.number,
      surahName: surah.name
    };
  });
}

const ALL_TAFSIR_FAMOUS = TAFSIR_SURAHS.flatMap(tafsirFamousAyahs);

